"""Generate Runnify's favicon set from one geometric definition.

The mark is a song lane read as levels: four bars on a near-black tile, the
tallest in volt for the song that lifts the pace most, like the covers saved
playlists get. The heights rise and fall like music, so it never reads as a
signal-strength icon. Shapes are rounded rectangles on a
32-unit grid, drawn with exact coverage on their straight parts and 8 x 8
supersampling on their corners. Standard library only.

The browser favicon is a rounded tile on a transparent ground. The app icons
(Apple touch icon and the manifest's icons) fill their whole square, because
phones cut their own shape, and keep the bars inside the central safe zone so
a round or squircle mask never clips them.

Run from the repository root:

    uv run python scripts/build_icons.py

Writes to runnify/static/img/: favicon.svg, favicon.ico (16, 32, 48 px),
apple-touch-icon.png (180 px), icon-192.png, icon-512.png and
runnify/static/site.webmanifest. Each PNG records this script as its source.
"""

import json
import struct
import zlib
from pathlib import Path

TILE = (0x0E, 0x10, 0x13)
BAR = (0x5B, 0x62, 0x6B)
VOLT = (0xD4, 0xFF, 0x3A)

GRID = 32
TILE_RADIUS = 7
# (x, y, width, height, corner radius, colour) on the 32-unit grid, drawn over the tile
BARS = (
    (5, 15.5, 4, 10, 1.25, BAR),
    (11, 9.5, 4, 16, 1.25, BAR),
    (17, 18.5, 4, 7, 1.25, BAR),
    (23, 5.5, 4, 20, 1.25, VOLT),  # the power song
)
APP_ICON_SCALE = 0.8  # the bars, scaled about the centre, sit inside the maskable safe zone

OUT = Path(__file__).resolve().parent.parent / "runnify" / "static"
SOURCE_NOTE = "Generated by scripts/build_icons.py (Runnify song-levels mark)"
SAMPLES = 8


def _inside(sx, sy, x0, y0, x1, y1, radius):
    """Whether the point (sx, sy) lies in the rounded rectangle."""
    if not (x0 <= sx < x1 and y0 <= sy < y1):
        return False
    cx = x0 + radius if sx < x0 + radius else x1 - radius if sx > x1 - radius else sx
    cy = y0 + radius if sy < y0 + radius else y1 - radius if sy > y1 - radius else sy
    return (sx - cx) ** 2 + (sy - cy) ** 2 <= radius**2


def _coverage(px, py, x0, y0, x1, y1, radius):
    """Fraction of the unit pixel at (px, py) covered by a rounded rectangle."""
    width = max(0.0, min(px + 1, x1) - max(px, x0))
    height = max(0.0, min(py + 1, y1) - max(py, y0))
    if not width or not height:
        return 0.0
    near_corner = (px < x0 + radius or px + 1 > x1 - radius) and (
        py < y0 + radius or py + 1 > y1 - radius
    )
    if not near_corner or radius <= 0:
        return width * height
    step = 1 / SAMPLES
    hits = sum(
        _inside(px + (i + 0.5) * step, py + (j + 0.5) * step, x0, y0, x1, y1, radius)
        for i in range(SAMPLES)
        for j in range(SAMPLES)
    )
    return hits / SAMPLES**2


def _paint(pixels, size, shape, colour):
    """Composite ``colour`` over ``pixels`` (RGBA lists) wherever ``shape`` covers them."""
    x0, y0, x1, y1, radius = shape
    for py in range(max(0, int(y0)), min(size, int(y1) + 1)):
        for px in range(max(0, int(x0)), min(size, int(x1) + 1)):
            alpha = _coverage(px, py, x0, y0, x1, y1, radius)
            if not alpha:
                continue
            pixel = pixels[py][px]
            keep = pixel[3] / 255 * (1 - alpha)
            total = alpha + keep
            for c in range(3):
                pixel[c] = round((colour[c] * alpha + pixel[c] * keep) / total)
            pixel[3] = round(total * 255)


def render(size, app_icon=False):
    """``size`` x ``size`` RGBA rows: a rounded tile for the favicon, a full square for app icons."""
    scale = size / GRID
    pixels = [[[0, 0, 0, 0] for _ in range(size)] for _ in range(size)]
    tile_radius = 0 if app_icon else TILE_RADIUS * scale
    _paint(pixels, size, (0, 0, size, size, tile_radius), TILE)
    shrink = APP_ICON_SCALE if app_icon else 1.0
    middle = GRID / 2
    for x, y, w, h, r, colour in BARS:
        x0 = (middle + (x - middle) * shrink) * scale
        y0 = (middle + (y - middle) * shrink) * scale
        _paint(
            pixels,
            size,
            (x0, y0, x0 + w * shrink * scale, y0 + h * shrink * scale, r * shrink * scale),
            colour,
        )
    return pixels


def _chunk(kind, data):
    body = kind + data
    return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)


def png(size, app_icon=False):
    """Encode the mark as an RGBA PNG with a tEXt chunk naming its source."""
    rows = render(size, app_icon)
    raw = b"".join(b"\x00" + bytes(v for pixel in row for v in pixel) for row in rows)
    return b"".join(
        [
            b"\x89PNG\r\n\x1a\n",
            _chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)),
            _chunk(b"tEXt", b"Source\x00" + SOURCE_NOTE.encode("latin-1")),
            _chunk(b"IDAT", zlib.compress(raw, 9)),
            _chunk(b"IEND", b""),
        ]
    )


def ico(sizes):
    """Pack PNG images of ``sizes`` into a .ico file."""
    images = [png(size) for size in sizes]
    offset = 6 + 16 * len(images)
    header = struct.pack("<HHH", 0, 1, len(images))
    entries = b""
    for size, data in zip(sizes, images, strict=True):
        entries += struct.pack("<BBBBHHII", size % 256, size % 256, 0, 0, 1, 32, len(data), offset)
        offset += len(data)
    return header + entries + b"".join(images)


def svg():
    """The favicon as SVG (used by browsers that support SVG favicons)."""
    hex_colour = "#{:02X}{:02X}{:02X}".format
    bars = "".join(
        f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{hex_colour(*c)}"/>'
        for x, y, w, h, r, c in BARS
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {GRID} {GRID}">'
        f'<rect width="{GRID}" height="{GRID}" rx="{TILE_RADIUS}" fill="{hex_colour(*TILE)}"/>'
        f"{bars}</svg>\n"
    )


def manifest():
    return {
        "name": "Runnify",
        "short_name": "Runnify",
        "description": "Find the songs that make you run faster.",
        "start_url": "/dashboard",
        "display": "standalone",
        "background_color": "#0E1013",
        "theme_color": "#0E1013",
        "icons": [
            {
                "src": "/static/img/icon-192.png",
                "sizes": "192x192",
                "type": "image/png",
                "purpose": "any maskable",
            },
            {
                "src": "/static/img/icon-512.png",
                "sizes": "512x512",
                "type": "image/png",
                "purpose": "any maskable",
            },
        ],
    }


def main():
    img = OUT / "img"
    img.mkdir(parents=True, exist_ok=True)
    (img / "favicon.svg").write_text(svg(), encoding="utf-8", newline="\n")
    (img / "favicon.ico").write_bytes(ico([16, 32, 48]))
    (img / "apple-touch-icon.png").write_bytes(png(180, app_icon=True))
    (img / "icon-192.png").write_bytes(png(192, app_icon=True))
    (img / "icon-512.png").write_bytes(png(512, app_icon=True))
    (OUT / "site.webmanifest").write_text(
        json.dumps(manifest(), indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    print(f"Wrote the favicon set to {img}")


if __name__ == "__main__":
    main()
